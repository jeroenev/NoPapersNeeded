/**
 * The model price snapshot the app ships for offline and first-run use: models.dev's list prices,
 * trimmed to the providers the app talks to, as one `provider<TAB>model<TAB>input<TAB>output` line
 * per model (US dollars per million tokens).
 *
 * The snapshot is committed (`core/pricing/models-dev.tsv`), so a build never touches the network
 * and every build of a commit prices the same way: the committed file is the pin, as a checksum
 * is for rclone. [UpdateModelPricesTask] refreshes it on demand, and its diff is reviewed like any
 * other change; [GenerateModelPriceSnapshotTask] turns it into the Kotlin the app compiles.
 */
object ModelPrices {
    /** What a model id may hold: safe in a Kotlin string literal and in the TSV as it stands. */
    private val ID = Regex("[A-Za-z0-9._:/@+-]+")

    /** Kotlin string constants stay well under the JVM's 64 KiB limit per constant. */
    private const val CHUNK_CHARS = 30_000

    /**
     * The snapshot of [apiJson] (models.dev's `api.json`) for [providers]: every model with a
     * numeric input and output price, sorted, under a header naming where and when it came from.
     * Models without a price, and ids that would not survive as a literal, are left out.
     */
    fun trim(
        apiJson: String,
        providers: List<String>,
        fetched: LocalDate,
        source: String,
    ): String {
        val root = JsonSlurper().parseText(apiJson) as? Map<*, *> ?: throw GradleException("$source is not an object")
        val lines =
            providers
                .flatMap { provider ->
                    val models =
                        (root[provider] as? Map<*, *>)?.get("models") as? Map<*, *>
                            ?: throw GradleException("$source has no provider \"$provider\"")
                    models.mapNotNull { (id, model) -> line(provider, id as? String, model as? Map<*, *>) }
                }.sorted()
        return buildString {
            append("# Model list prices in US dollars per million tokens: provider, model, input, output.\n")
            append("# From $source, fetched $fetched. Refresh: ./gradlew :core:updateModelPrices\n")
            lines.forEach { append(it).append('\n') }
        }
    }

    private fun line(
        provider: String,
        id: String?,
        model: Map<*, *>?,
    ): String? {
        if (id == null || !ID.matches(id)) return null
        val cost = model?.get("cost") as? Map<*, *> ?: return null
        val input = price(cost["input"]) ?: return null
        val output = price(cost["output"]) ?: return null
        return "$provider\t$id\t$input\t$output"
    }

    private fun price(value: Any?): String? =
        (value as? Number)
            ?.let { BigDecimal(it.toString()) }
            ?.takeIf { it.signum() >= 0 }
            ?.stripTrailingZeros()
            ?.toPlainString()

    /**
     * The Kotlin source of `dev.npn.core.ai.AiPriceSnapshot` for [tsv], refusing a snapshot whose
     * lines are not what [trim] writes: hand edits are reviewed, but a malformed line must fail the
     * build rather than ship as a wrong price.
     */
    fun kotlinSource(tsv: String): String {
        val lines = tsv.lines().filter { it.isNotBlank() && !it.startsWith("#") }
        lines.forEachIndexed { index, line -> check(line, index) }
        val chunks = chunked(lines)
        return buildString {
            append("package dev.npn.core.ai\n\n")
            append("/** Generated by :core:generateModelPriceSnapshot from core/pricing/models-dev.tsv. */\n")
            append("internal object AiPriceSnapshot {\n")
            append("    /** One `provider<TAB>model<TAB>input<TAB>output` line per model, USD per million tokens. */\n")
            append("    val TSV: String\n")
            append("        get() = ")
            append(chunks.indices.joinToString(" + ") { "PART_$it" }.ifEmpty { "\"\"" })
            append("\n")
            chunks.forEachIndexed { index, chunk ->
                append("\n    private const val PART_$index =\n        \"")
                append(chunk.replace("\t", "\\t").replace("\n", "\\n"))
                append("\"\n")
            }
            append("}\n")
        }
    }

    private fun check(
        line: String,
        index: Int,
    ) {
        val fields = line.split('\t')
        val valid =
            fields.size == 4 &&
                ID.matches(fields[0]) &&
                ID.matches(fields[1]) &&
                fields[2].toBigDecimalOrNull()?.signum()?.let { it >= 0 } == true &&
                fields[3].toBigDecimalOrNull()?.signum()?.let { it >= 0 } == true
        if (!valid) throw GradleException("Model price snapshot line ${index + 1} is malformed: \"$line\"")
    }

    private fun chunked(lines: List<String>): List<String> {
        val chunks = mutableListOf<String>()
        val current = StringBuilder()
        for (line in lines) {
            if (current.isNotEmpty() && current.length + line.length + 1 > CHUNK_CHARS) {
                chunks += current.toString()
                current.clear()
            }
            current.append(line).append('\n')
        }
        if (current.isNotEmpty()) chunks += current.toString()
        return chunks
    }
}

/**
 * Downloads models.dev's catalog and rewrites the committed snapshot from it. Never part of a
 * build: run it by hand to refresh prices, and review the diff.
 */
@UntrackedTask(because = "It reads the live catalog, which changes without notice.")
abstract class UpdateModelPricesTask : DefaultTask() {
    @get:Input
    abstract val url: Property<String>

    /** models.dev's provider ids, one per provider the app prices. */
    @get:Input
    abstract val providers: ListProperty<String>

    @get:OutputFile
    abstract val snapshot: RegularFileProperty

    @TaskAction
    fun update() {
        val source = url.get()
        logger.lifecycle("Downloading $source")
        val connection =
            URI(source).toURL().openConnection().apply {
                connectTimeout = TIMEOUT_MS
                readTimeout = TIMEOUT_MS
            }
        val body = connection.getInputStream().use { it.readBytes().decodeToString() }
        val trimmed = ModelPrices.trim(body, providers.get(), LocalDate.now(ZoneOffset.UTC), source)
        // Fails here rather than in the next build when the catalog changed shape.
        ModelPrices.kotlinSource(trimmed)
        snapshot.get().asFile.writeText(trimmed)
    }

    private companion object {
        const val TIMEOUT_MS = 60_000
    }
}

/** Writes `dev.npn.core.ai.AiPriceSnapshot` from the committed snapshot; see [ModelPrices]. */
abstract class GenerateModelPriceSnapshotTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val snapshot: RegularFileProperty

    @get:OutputDirectory
    abstract val outDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outDir.file("dev/npn/core/ai/AiPriceSnapshot.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(ModelPrices.kotlinSource(snapshot.get().asFile.readText()))
    }
}
