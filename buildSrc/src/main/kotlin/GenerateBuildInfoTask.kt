import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes `dev.npn.app.BuildInfo`, so the UI shows the version from gradle.properties instead of a
 * constant that has to be kept in sync by hand, and the cloud setup signs in to Google Drive with
 * this build's own OAuth app when one is configured (`npn.drive.clientId`/`npn.drive.clientSecret`,
 * or `NPN_DRIVE_CLIENT_ID`/`NPN_DRIVE_CLIENT_SECRET`). Left blank, the wizard falls back to rclone's
 * shared app.
 */
abstract class GenerateBuildInfoTask : DefaultTask() {
    @get:Input
    abstract val version: Property<String>

    @get:Input
    abstract val driveClientId: Property<String>

    @get:Input
    abstract val driveClientSecret: Property<String>

    @get:OutputDirectory
    abstract val outDir: DirectoryProperty

    init {
        driveClientId.convention("")
        driveClientSecret.convention("")
    }

    @TaskAction
    fun generate() {
        val clientId = literal("Drive client id", driveClientId.get())
        val clientSecret = literal("Drive client secret", driveClientSecret.get())
        if (clientId.isEmpty() != clientSecret.isEmpty()) {
            throw GradleException("Set both npn.drive.clientId and npn.drive.clientSecret, or neither.")
        }
        val file = outDir.file("dev/npn/app/BuildInfo.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            package dev.npn.app

            /** Generated by :composeApp:generateBuildInfo from gradle.properties and the build's environment. */
            object BuildInfo {
                const val VERSION = "${version.get()}"

                /** This build's Google OAuth client for Drive sign-in; blank means rclone's shared one. */
                const val DRIVE_CLIENT_ID = "$clientId"

                /** An installed app's OAuth client secret, which Google does not treat as confidential. */
                const val DRIVE_CLIENT_SECRET = "$clientSecret"
            }
            """.trimIndent() + "\n",
        )
    }

    /** [value] trimmed, refused unless it is safe inside a Kotlin string literal as it stands. */
    private fun literal(
        what: String,
        value: String,
    ): String {
        val trimmed = value.trim()
        if (!OAUTH_VALUE.matches(trimmed)) throw GradleException("$what holds characters an OAuth value never has.")
        return trimmed
    }

    private companion object {
        /** What Google's client ids (`….apps.googleusercontent.com`) and secrets (`GOCSPX-…`) are made of. */
        val OAUTH_VALUE = Regex("[A-Za-z0-9._-]*")
    }
}
