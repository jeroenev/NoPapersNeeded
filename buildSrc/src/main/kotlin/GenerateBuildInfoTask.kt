import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes `dev.npn.app.BuildInfo`, so the UI shows the version from gradle.properties instead of a
 * constant that has to be kept in sync by hand.
 */
abstract class GenerateBuildInfoTask : DefaultTask() {
    @get:Input
    abstract val version: Property<String>

    @get:OutputDirectory
    abstract val outDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outDir.file("dev/npn/app/BuildInfo.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            package dev.npn.app

            /** Generated by :composeApp:generateBuildInfo from npn.version in gradle.properties. */
            object BuildInfo {
                const val VERSION = "${version.get()}"
            }
            """.trimIndent() + "\n",
        )
    }
}
