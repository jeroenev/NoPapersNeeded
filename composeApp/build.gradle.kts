// Writes dev.npn.app.BuildInfo, so the UI shows the version from gradle.properties instead of a
// constant that has to be kept in sync by hand.
abstract class GenerateBuildInfoTask : DefaultTask() {
    @get:Input
    abstract val version: Property<String>

    @get:OutputDirectory
    abstract val outDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outDir.file("dev/npn/app/BuildInfo.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            package dev.npn.app

            /** Generated by :composeApp:generateBuildInfo from npn.version in gradle.properties. */
            object BuildInfo {
                const val VERSION = "${version.get()}"
            }
            """.trimIndent() + "\n",
        )
    }
}

val generateBuildInfo =
    tasks.register<GenerateBuildInfoTask>("generateBuildInfo") {
        version.set(NpnVersion.of(project).name)
        outDir.set(layout.buildDirectory.dir("generated/buildInfo/commonMain/kotlin"))
    }

kotlin {
    jvmToolchain(
        libs.versions.jdk
            .get()
            .toInt(),
    )
    jvm("desktop") {
        compilerOptions {
            jvmTarget =
                JvmTarget.fromTarget(
                    libs.versions.jvm.target
                        .get(),
                )
            freeCompilerArgs.add("-Xjdk-release=${libs.versions.jvm.target.get()}")
        }
    }

    androidLibrary {
        namespace = "dev.npn.app"
        compileSdk =
            libs.versions.android.compileSdk
                .get()
                .toInt()
        minSdk =
            libs.versions.android.minSdk
                .get()
                .toInt()

        compilerOptions {
            jvmTarget =
